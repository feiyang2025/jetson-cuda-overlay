#!/usr/bin/env python3
"""Install the branch-adaptive patch layer into a fork's tree.

What it writes, and why it is not "copy a whole file over the tree":

1. `<tree>/<pkg>/selfdrive/modeld/cuda_adapter.py` - the adapter itself (one
   file, never edits a fork file);
2. `<tree>/sitecustomize.py` - CPython imports this at interpreter start for
   every process when the tree root is on sys.path, which the device launcher
   does through PYTHONPATH. It only calls `cuda_adapter.apply()`.

If the tree already has a `sitecustomize.py` that imports its own patch module
(e.g. master-c3's `cuda_patches`), that file is left ALONE: the fork's own hook
already fires, and this installer only drops the adapter next to it for the
layout/registry helpers. Nothing is overwritten without a `.before_patch_layer`
backup.

Usage:
  python3 install_patch.py <tree-root> [--force]
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ADAPTER_MARKER = "Fork-adaptive CUDA/TensorRT runtime patch layer"
BACKUP_SUFFIX = ".before_patch_layer"

SITECUSTOMIZE = '''"""Fork hook: apply the CUDA/TensorRT patch layer in every python process.

CPython imports this module automatically at interpreter start (for `python -c`,
`python -m` and scripts alike) as long as this directory is on `sys.path`. The
device launcher puts the checkout root there through PYTHONPATH
(launch_chffrplus.sh), which the manager and its children inherit. That is the one
place a patch can run before user code without editing an upstream file.

Keep this file tiny and defensive: it runs in every python process on the device,
so it only delegates and swallows every failure. `OPENPILOT_CUDA_PATCH=0` disables
the patches (read by the adapter at call time).

Generated by jetson-cuda-overlay kits/patch/install_patch.py.
"""

import sys

if "openpilot" in sys.modules or __name__ == "__main__":
  import os

  if os.environ.get("OPENPILOT_CUDA_PATCH", "1") != "0":
    try:
      from openpilot.selfdrive.modeld import cuda_adapter

      cuda_adapter.apply()
    except Exception:
      pass
'''


def find_modeld_dir(tree: Path) -> Path | None:
  """Package-relative selfdrive/modeld, new layout (openpilot/) first."""
  for candidate in (tree / "openpilot" / "selfdrive" / "modeld",
                    tree / "selfdrive" / "modeld"):
    if candidate.is_dir():
      return candidate
  return None


def install(tree: Path, force: bool = False) -> int:
  adapter_src = Path(__file__).with_name("cuda_adapter.py")
  if not adapter_src.is_file():
    print(f"ERROR: {adapter_src} missing (run from the overlay's kits/patch)")
    return 1

  modeld_dir = find_modeld_dir(tree)
  if modeld_dir is None:
    print(f"ERROR: {tree} has no selfdrive/modeld; not an openpilot tree")
    return 1

  changed = 0

  # 1. adapter (幂等: 已有本 kit 标记就跳过)
  dst = modeld_dir / "cuda_adapter.py"
  if dst.is_file():
    existing = dst.read_text(encoding="utf-8", errors="ignore")
    if not force and ADAPTER_MARKER in existing:
      print(f"  - {dst.name} already installed (idempotent), kept")
    else:
      shutil.copy2(dst, dst.with_name(dst.name + BACKUP_SUFFIX))
      shutil.copy2(adapter_src, dst)
      print(f"  + {dst.relative_to(tree)} (backup: {dst.name}{BACKUP_SUFFIX})")
      changed += 1
  else:
    shutil.copy2(adapter_src, dst)
    print(f"  + {dst.relative_to(tree)}")
    changed += 1

  # 2. sitecustomize
  sc = tree / "sitecustomize.py"
  if sc.is_file():
    text = sc.read_text(encoding="utf-8", errors="ignore")
    if "cuda_adapter" in text:
      print("  - sitecustomize.py already imports cuda_adapter, kept")
    elif "cuda_patches" in text or "cuda_overlay" in text:
      print("  - sitecustomize.py already imports a fork patch module, kept (adapter is available for its use)")
    else:
      shutil.copy2(sc, sc.with_name(sc.name + BACKUP_SUFFIX))
      import io
      # Append rather than replace: an unknown hook in the file must keep working.
      with open(sc, "a", encoding="utf-8") as f:
        f.write('\n\n# --- jetson-cuda-overlay patch layer (appended) ---\n'
                'import os as _cuda_os\n'
                'if _cuda_os.environ.get("OPENPILOT_CUDA_PATCH", "1") != "0":\n'
                '  try:\n'
                '    from openpilot.selfdrive.modeld import cuda_adapter\n'
                '    cuda_adapter.apply()\n'
                '  except Exception:\n'
                '    pass\n')
      print(f"  + sitecustomize.py (appended adapter hook; backup {sc.name}{BACKUP_SUFFIX})")
      changed += 1
  else:
    sc.write_text(SITECUSTOMIZE, encoding="utf-8")
    print(f"  + sitecustomize.py")
    changed += 1

  print(f"  -> patch layer: {dst}")
  if changed == 0:
    print("  (nothing changed)")
  return 0


def main() -> int:
  ap = argparse.ArgumentParser(description="Install the CUDA patch layer into an openpilot tree")
  ap.add_argument("tree", help="fork root (contains openpilot/ or selfdrive/)")
  ap.add_argument("--force", action="store_true", help="replace an existing adapter file")
  args = ap.parse_args()
  tree = Path(args.tree).expanduser().resolve()
  print(f"[install_patch] {tree}")
  return install(tree, args.force)


if __name__ == "__main__":
  raise SystemExit(main())
